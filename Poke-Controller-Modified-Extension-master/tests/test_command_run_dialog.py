"""Commands dialog recovery without camera, serial or game input."""
import ast
import copy
import sys
import types
import unittest
from pathlib import Path
from unittest import mock

SERIAL = Path(__file__).resolve().parents[1] / "SerialController"
sys.path.insert(0, str(SERIAL))


def window_methods(*names):
    path = SERIAL / "Window.py"
    tree = ast.parse(path.read_text(encoding="utf-8-sig"))
    owner = next(n for n in tree.body if isinstance(n, ast.ClassDef)
                 and n.name == "PokeControllerApp")
    methods = [copy.deepcopy(n) for n in owner.body
               if isinstance(n, ast.FunctionDef) and n.name in names]
    namespace = {}
    exec(compile(ast.fix_missing_locations(ast.Module(
        body=methods, type_ignores=[])), str(path), "exec"), namespace)
    return types.SimpleNamespace(**{name: namespace[name] for name in names})


class PendingDialogEntrypointTests(unittest.TestCase):
    def test_start_shortcut_and_reload_reactivate_without_rebinding(self):
        methods = window_methods("startPlay", "startShortcutPlay", "reloadCommands")
        for name in ("startPlay", "startShortcutPlay", "reloadCommands"):
            with self.subTest(name=name):
                existing = object()
                app = types.SimpleNamespace(
                    _command_run_dialog=mock.Mock(), _commands_loaded=False,
                    cur_command=existing, show_output=mock.Mock(),
                    _cancel_command_debug_pulse=mock.Mock(),
                    _state_value_cache={}, assignCommand=mock.Mock(),
                    assignShortcutCommand=mock.Mock())
                getattr(methods, name)(app)
                app._command_run_dialog.activate.assert_called_once_with()
                app.show_output.assert_not_called()
                app.assignCommand.assert_not_called()
                app.assignShortcutCommand.assert_not_called()
                app._cancel_command_debug_pulse.assert_not_called()
                self.assertIs(app.cur_command, existing)


class DialogLifecycleTests(unittest.TestCase):
    def setUp(self):
        import tkinter as tk
        import CommandRunDialog as module
        self.module = module
        self.root = tk.Tk()
        self.root.withdraw()
        self.app = types.SimpleNamespace(root=self.root)

    def tearDown(self):
        self.root.destroy()

    def test_reentrant_request_keeps_same_dialog_and_edited_value(self):
        import tkinter as tk
        entered = []

        @self.module.single_command_run_dialog
        def prompt(app):
            dialog = tk.Toplevel(self.root)
            app._command_run_dialog.attach(dialog)
            entry = tk.Entry(dialog)
            entry.insert(0, "edited pending Step")
            entered.append(dialog)
            with mock.patch.object(app._command_run_dialog, "activate") as activate:
                self.assertFalse(prompt(app))
                activate.assert_called_once_with()
            self.assertIs(app._command_run_dialog.dialog, dialog)
            self.assertEqual(entry.get(), "edited pending Step")
            return False

        self.assertFalse(prompt(self.app))
        self.assertEqual(len(entered), 1)
        self.assertFalse(entered[0].winfo_exists())
        self.assertIsNone(self.app._command_run_dialog)

    def test_build_exception_destroys_dialog_and_restores_next_request(self):
        import tkinter as tk
        dialogs = []

        @self.module.single_command_run_dialog
        def prompt(app, fail):
            dialog = tk.Toplevel(self.root)
            app._command_run_dialog.attach(dialog)
            dialogs.append(dialog)
            dialog.grab_set()
            if fail:
                raise ValueError("invalid saved setting")
            return True

        with self.assertRaisesRegex(ValueError, "invalid saved setting"):
            prompt(self.app, True)
        self.assertIsNone(self.root.grab_current())
        self.assertIsNone(self.app._command_run_dialog)
        self.assertFalse(dialogs[0].winfo_exists())
        self.assertTrue(prompt(self.app, False))
        self.assertFalse(dialogs[1].winfo_exists())

    def test_local_grab_parent_click_and_f5_f6_request_existing_dialog(self):
        import tkinter as tk
        manager = self.module.CommandRunDialog(self.app)
        dialog = tk.Toplevel(self.root)
        manager.attach(dialog)
        button = tk.Button(self.root, text="Start")
        dialog.grab_set()
        self.assertIs(self.root.grab_current(), dialog)
        with mock.patch.object(manager, "activate") as activate, \
                mock.patch.object(self.root, "winfo_containing", return_value=button):
            # Deliver the same redirected event generated by a local Tk grab.
            dialog.event_generate("<ButtonPress-1>", rootx=45, rooty=55)
            self.assertEqual(activate.call_count, 1)
            for key in ("<F5>", "<F6>"):
                binding = dialog.bind(key)
                self.assertTrue(binding)
                callback = binding.split("[")[1].split()[0]
                self.root.tk.call(callback)  # Invoke the registered Tcl handler.
            self.assertEqual(activate.call_count, 3)
        manager.close()
        self.assertIsNone(self.root.grab_current())

    def test_parent_handler_ignores_controls_inside_dialog_and_other_windows(self):
        import tkinter as tk
        manager = self.module.CommandRunDialog(self.app)
        dialog = tk.Toplevel(self.root)
        manager.attach(dialog)
        entry = tk.Entry(dialog)
        other = tk.Toplevel(self.root)
        other.withdraw()
        event = types.SimpleNamespace(x_root=10, y_root=20)
        with mock.patch.object(manager, "activate") as activate:
            for widget in (entry, other, None):
                with mock.patch.object(self.root, "winfo_containing", return_value=widget):
                    self.assertIsNone(manager._parent_click(event))
            activate.assert_not_called()
        manager.close()

    def test_close_removes_only_own_focus_binding(self):
        import tkinter as tk
        original = self.root.bind("<FocusIn>", lambda event: None, add="+")
        manager = self.module.CommandRunDialog(self.app)
        manager.attach(tk.Toplevel(self.root))
        added = manager._focus_binding
        self.assertIn(original, self.root.bind("<FocusIn>"))
        self.assertIn(added, self.root.bind("<FocusIn>"))
        manager.close()
        self.assertIn(original, self.root.bind("<FocusIn>"))
        self.assertNotIn(added, self.root.bind("<FocusIn>"))

    def test_real_step_selector_cancel_and_reentrant_start_do_not_run_game(self):
        import tkinter as tk
        from tkinter import ttk
        from CommandRunOptions import preserve_location_selection
        path = SERIAL / "Window.py"
        tree = ast.parse(path.read_text(encoding="utf-8-sig"))
        method = next(n for n in ast.walk(tree)
                      if isinstance(n, ast.FunctionDef)
                      and n.name == "_prompt_command_run_settings")
        namespace = {"tk": tk, "ttk": ttk, "copy": copy, "os": __import__("os"),
                     "__file__": str(path),
                     "preserve_location_selection": preserve_location_selection,
                     "single_command_run_dialog": self.module.single_command_run_dialog,
                     "build_native_image_collection_controls": lambda *a: mock.Mock()}
        exec(compile(ast.fix_missing_locations(ast.Module(
            body=[method], type_ignores=[])), str(path), "exec"), namespace)
        location = {"id": "step", "label": "Step", "variable": "state", "value": "STEP"}
        app = self.app
        app._command_run_options = lambda name: {"enabled": True, "locations": [location]}
        app.command_start_overrides = {}
        app.command_run_favorites = {}
        app._command_run_location_display = lambda item: item["label"]
        app._refresh_command_start_status = mock.Mock()
        app._sync_command_start_overrides_to_active_input_set = mock.Mock()
        command = types.SimpleNamespace(NAME="Fake command", COMMAND_RUN_SETTINGS=True)
        observed = []

        def present(manager):
            observed.append(manager.dialog)
            manager.dialog.grab_set()
            self.assertFalse(namespace["_prompt_command_run_settings"](app, command))
            self.root.after(5, lambda: self.root.tk.call(
                manager.dialog.protocol("WM_DELETE_WINDOW")))

        with mock.patch.object(self.module.CommandRunDialog, "present", present), \
                mock.patch.object(self.module.CommandRunDialog, "activate"):
            self.assertFalse(namespace["_prompt_command_run_settings"](app, command))
        self.assertEqual(len(observed), 1)
        self.assertFalse(observed[0].winfo_exists())
        self.assertIsNone(self.root.grab_current())
        self.assertIsNone(app._command_run_dialog)
        self.assertEqual(app.command_start_overrides, {})
        app._sync_command_start_overrides_to_active_input_set.assert_not_called()


class DialogActivationTests(unittest.TestCase):
    def setUp(self):
        import CommandRunDialog as module
        self.module = module
        self.root = mock.Mock()
        self.manager = module.CommandRunDialog(types.SimpleNamespace(root=self.root))
        self.dialog = mock.Mock(master=self.root)
        self.dialog.winfo_exists.return_value = True
        self.dialog.state.return_value = "normal"
        self.dialog.focus_lastfor.return_value = self.dialog
        self.manager.dialog = self.dialog
        self.root.grab_current.return_value = self.dialog

    def test_foreground_request_restores_minimized_and_repairs_offscreen_position(self):
        self.dialog.state.return_value = "iconic"
        with mock.patch.object(self.module, "dialog_owner_attachment_allowed", return_value=True), \
                mock.patch.object(self.module, "_place_on_owner_monitor") as position:
            self.manager.activate()
        self.dialog.deiconify.assert_called_once_with()
        self.dialog.lift.assert_called_once_with()
        self.dialog.focus_set.assert_called_once_with()
        position.assert_called_once_with(self.dialog, self.root)
        self.root.lift.assert_not_called()
        self.dialog.attributes.assert_not_called()

    def test_other_application_foreground_never_raises_or_moves_any_window(self):
        with mock.patch.object(self.module, "dialog_owner_attachment_allowed", return_value=False), \
                mock.patch.object(self.module, "_place_on_owner_monitor") as position:
            self.manager.activate()
        self.dialog.lift.assert_not_called()
        self.dialog.deiconify.assert_not_called()
        self.dialog.focus_set.assert_not_called()
        position.assert_not_called()

    def test_nested_confirmation_keeps_grab_and_focus(self):
        nested = mock.Mock(master=self.dialog)
        nested.state.return_value = "normal"
        nested.winfo_toplevel.return_value = nested
        nested.focus_lastfor.return_value = nested
        self.root.grab_current.return_value = nested
        with mock.patch.object(self.module, "dialog_owner_attachment_allowed", return_value=True), \
                mock.patch.object(self.module, "_place_on_owner_monitor"):
            self.manager.activate()
        nested.lift.assert_called_once_with()
        nested.focus_set.assert_called_once_with()
        self.dialog.lift.assert_not_called()
        self.dialog.grab_set.assert_not_called()
        nested.grab_release.assert_not_called()

    def test_geometry_recovers_on_negative_coordinate_monitor(self):
        dialog = self.dialog
        dialog.winfo_width.return_value = 1020
        dialog.winfo_height.return_value = 720
        dialog.winfo_rootx.return_value = 5000
        dialog.winfo_rooty.return_value = 3000
        dialog.minsize.return_value = (820, 620)
        self.root.winfo_rootx.return_value = -1920
        self.root.winfo_rooty.return_value = 0
        self.root.winfo_width.return_value = 1920
        self.root.winfo_height.return_value = 1040
        with mock.patch.object(self.module, "_owner_work_area", return_value=(-1920, 0, 0, 1040)):
            self.module._place_on_owner_monitor(dialog, self.root)
        dialog.geometry.assert_called_once_with("1020x720+-1470+160")

    def test_visible_dialog_position_is_preserved(self):
        dialog = self.dialog
        dialog.winfo_width.return_value = 1020
        dialog.winfo_height.return_value = 720
        dialog.winfo_rootx.return_value = 100
        dialog.winfo_rooty.return_value = 100
        with mock.patch.object(self.module, "_owner_work_area", return_value=(0, 0, 1920, 1040)):
            self.module._place_on_owner_monitor(dialog, self.root)
        dialog.geometry.assert_not_called()


